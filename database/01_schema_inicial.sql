-- Script DDL Inicial do OportunizaHub (Aula 09)

-- 1. Tabela de Oportunidades
CREATE TABLE IF NOT EXISTS oportunidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(100) NOT NULL,
    tipo_categoria VARCHAR(20) NOT NULL,
    instituicao_empresa VARCHAR(100) NOT NULL,
    descricao_requisitos TEXT NOT NULL,
    link_ou_contato VARCHAR(255) NOT NULL,
    status VARCHAR(10) DEFAULT 'ativa' NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 2. Tabela de Log de Visualizações (RF-03)
CREATE TABLE IF NOT EXISTS visualizacoes_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oportunidade_id BIGINT REFERENCES oportunidades(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- 3. Habilitar RLS (Row Level Security)
ALTER TABLE oportunidades ENABLE ROW LEVEL SECURITY;
ALTER TABLE visualizacoes_log ENABLE ROW LEVEL SECURITY;

-- 4. Políticas Temporárias de Acesso Público para o MVP 1
CREATE POLICY "Acesso público leitura oportunidades" 
ON oportunidades FOR SELECT USING (true);

CREATE POLICY "Acesso público escrita oportunidades" 
ON oportunidades FOR INSERT WITH CHECK (true);

CREATE POLICY "Acesso público atualização oportunidades" 
ON oportunidades FOR UPDATE USING (true);

CREATE POLICY "Acesso público leitura e escrita logs" 
ON visualizacoes_log FOR ALL USING (true) WITH CHECK (true);